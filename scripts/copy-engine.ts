import { copyFile, mkdir, readdir, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'node_modules', 'stockfish', 'bin');
const target = path.join(root, 'public', 'engine');
const constantFile = path.join(root, 'src', 'modules', 'chess', 'engine', 'engineFiles.ts');

/** The lite, single-threaded Stockfish build: `stockfish-<version>-lite-single.{js,wasm}`. */
const LITE_SINGLE = /^stockfish-[\w.-]+?-lite-single\.(js|wasm)$/;

const names = (await readdir(source)).filter((name) => LITE_SINGLE.test(name)).sort();
const js = names.filter((n) => n.endsWith('.js'));
const wasm = names.filter((n) => n.endsWith('.wasm'));
if (js.length !== 1 || wasm.length !== 1) {
  throw new Error(`Expected one lite single-threaded .js and one .wasm in ${source}, found: ${names.join(', ') || 'none'}`);
}

await rm(target, { recursive: true, force: true });
await mkdir(target, { recursive: true });
// The engine script finds its WASM next to itself by its own file name, so the original names are kept.
for (const name of names) await copyFile(path.join(source, name), path.join(target, name));

const body = `/** Generated by scripts/copy-engine.ts: the Stockfish files copied to \`public/engine/\`. */
export const ENGINE_FILES = {
  script: '${js[0]}',
  wasm: '${wasm[0]}',
} as const;
`;
await mkdir(path.dirname(constantFile), { recursive: true });
await writeFile(constantFile, body);
console.log(`engine files copied: ${names.join(', ')}`);